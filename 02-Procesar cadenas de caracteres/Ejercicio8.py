'''
Inicializar un string con la cadena "mAriA" luego llamar a sus
métodos upper(), lower() y capitalize(), guardar los datos
retornados en otros string y mostrarlos por pantalla.
'''

cadena = "mAriA"
cadena1 = cadena.upper()
cadena2 = cadena.lower()
cadena3 = cadena.capitalize()

print({cadena1} , {cadena2} , {cadena3})